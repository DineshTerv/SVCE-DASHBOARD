// ── Today's submission distribution (0-15 questions) ─────────────────────────
export function getTodayDistribution() {
  const buckets = Array.from({ length: 16 }, (_, i) => ({ label: `${i}`, count: 0 }));
  for (const s of STUDENT_DATA) {
    const idx = Math.min(s.todayQ, 15);
    buckets[idx].count++;
  }
  return buckets;
}

// ── Cumulative till-date distribution ─────────────────────────────────────────
export function getTillDateDistribution() {
  const ranges = [
    { label: "0",    min: 0,  max: 0  },
    { label: "1-14", min: 1,  max: 14 },
    { label: "15-28",min: 15, max: 28 },
    { label: "29-42",min: 29, max: 42 },
    { label: "43-56",min: 43, max: 56 },
    { label: "57-70",min: 57, max: 70 },
    { label: "71-84",min: 71, max: 84 },
    { label: "85+",  min: 85, max: 999},
  ];
  return ranges.map(r => ({
    label: r.label,
    count: STUDENT_DATA.filter(s => s.tillDateQ >= r.min && s.tillDateQ <= r.max).length,
  }));
}

// ── Top performers ────────────────────────────────────────────────────────────
export function getTopPerformers(n = 5) {
  return [...STUDENT_DATA].sort((a, b) => b.tillDateQ - a.tillDateQ || b.todayQ - a.todayQ).slice(0, n);
}

// ── Needs attention (0 today or attendance < 70) ─────────────────────────────
export function getNeedsAttention(n = 5) {
  return [...STUDENT_DATA]
    .filter(s => s.todayQ === 0 || s.attendance < 70)
    .sort((a, b) => a.todayQ - b.todayQ || a.attendance - b.attendance)
    .slice(0, n);
}
